"""Run the 30-question test set through the agent and score it.

    python eval/run_eval.py                  all questions, default model
    python eval/run_eval.py --ids 3 14 25    a subset
    python eval/run_eval.py --provider gemini --pause 15   free tier: about 4 questions a minute

Needs ANTHROPIC_API_KEY (or GEMINI_API_KEY with --provider gemini). Writes reports/eval_results.md and reports/eval_results.csv.
"""
import argparse
import sys
import time
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from askdata import db  # noqa: E402
from askdata.graph import build_graph  # noqa: E402
from askdata.llm import make_llm  # noqa: E402
from askdata.scoring import matches  # noqa: E402

REPORTS = ROOT / "reports"


def run(ids: list[int] | None, provider: str | None, model: str | None,
        pause: float = 0) -> tuple[pd.DataFrame, str]:
    questions = yaml.safe_load((ROOT / "eval" / "questions.yaml").read_text(encoding="utf-8"))
    if ids:
        questions = [q for q in questions if q["id"] in ids]
    llm = make_llm(provider, model)
    graph = build_graph(llm, explain=False)
    rows = []
    for i, q in enumerate(questions):
        if i and pause:
            time.sleep(pause)  # stay under free-tier requests-per-minute limits
        gold = db.run_query(q["gold_sql"]).df
        start = time.perf_counter()
        state = graph.invoke({"question": q["question"]})
        seconds = time.perf_counter() - start
        ok = state.get("error") is None and "df" in state and matches(gold, state["df"])
        rows.append({"id": q["id"], "level": q["level"], "question": q["question"], "correct": ok,
                     "attempts": state.get("attempts", 0), "seconds": round(seconds, 1),
                     "error": state.get("error") or "", "sql": state.get("sql", "")})
        print(f"{q['id']:>2} {'PASS' if ok else 'FAIL'}  {seconds:5.1f}s  {state.get('attempts', 0)} try  "
              f"{q['question']}")
    return pd.DataFrame(rows), llm.model


def report(df: pd.DataFrame, model: str):
    REPORTS.mkdir(exist_ok=True)
    df.to_csv(REPORTS / "eval_results.csv", index=False)
    by_level = (df.groupby("level", sort=False)
                .agg(questions=("correct", "size"), correct=("correct", "sum"))
                .reindex(["easy", "medium", "hard"]).dropna())
    by_level["accuracy"] = by_level.correct / by_level.questions
    lines = [
        "# Eval results (generated by `python eval/run_eval.py`)", "",
        f"- Model: `{model}`",
        f"- Execution accuracy: **{df.correct.sum()}/{len(df)} ({df.correct.mean():.0%})**",
        f"- Answered on the first try: {(df.attempts == 1).mean():.0%}; "
        f"fixed by a retry: {((df.attempts > 1) & df.correct).sum()}",
        f"- Median time per question: {df.seconds.median():.1f}s (no explanation step)", "",
        "| Level | Questions | Correct | Accuracy |", "|---|---:|---:|---:|",
    ]
    for level, r in by_level.iterrows():
        lines.append(f"| {level} | {int(r.questions)} | {int(r.correct)} | {r.accuracy:.0%} |")
    lines += ["", "## Every question", "", "| # | Level | Question | Result | Tries |", "|---|---|---|---|---:|"]
    for r in df.itertuples():
        lines.append(f"| {r.id} | {r.level} | {r.question} | {'pass' if r.correct else 'FAIL'} | {r.attempts} |")
    misses = df[~df.correct]
    if len(misses):
        lines += ["", "## Misses", ""]
        for r in misses.itertuples():
            lines += [f"**{r.id}. {r.question}**", ""]
            if r.error:
                lines += [f"Error: {r.error}", ""]
            lines += ["```sql", r.sql.strip(), "```", ""]
    (REPORTS / "eval_results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\n{df.correct.sum()}/{len(df)} correct. Wrote {REPORTS / 'eval_results.md'}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ids", type=int, nargs="*")
    parser.add_argument("--provider", choices=["claude", "gemini"])
    parser.add_argument("--model")
    parser.add_argument("--pause", type=float, default=0, help="seconds between questions (free tiers)")
    args = parser.parse_args()
    report(*run(args.ids, args.provider, args.model, args.pause))


if __name__ == "__main__":
    main()
